def _translation_entries():
    return {
        (context, source): translated
        for source, translated in ZH_CN.items()
        for context in ("*", "Operator")
    }


TRANSLATIONS = {
    "zh_CN": _translation_entries(),
    "zh_HANS": _translation_entries(),
}


def register_translations():
    try:
        bpy.app.translations.unregister(DOMAIN)
    except RuntimeError:
        pass
    bpy.app.translations.register(DOMAIN, TRANSLATIONS)


def unregister_translations():
    try:
        bpy.app.translations.unregister(DOMAIN)
    except RuntimeError:
        pass


def iface(message):
    return bpy.app.translations.pgettext_iface(message)


def tip(message):
    return bpy.app.translations.pgettext_tip(message)
