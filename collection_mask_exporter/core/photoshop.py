import json
import os
from datetime import datetime, timezone

from .output_manager import blend_stem, ensure_output_dirs, safe_filename


class PhotoshopHandoffError(ValueError):
    pass


def _layer_name(path):
    stem = os.path.splitext(os.path.basename(path))[0]
    parent = os.path.basename(os.path.dirname(path)).lower()
    if parent == "masks":
        return f"Mask - {stem}"
    if parent == "color_id":
        return f"Color ID - {stem}"
    return stem


def _jsx_literal(value):
    return json.dumps(value, ensure_ascii=True)


def _handoff_entries(outputs):
    entries = []
    used_channels = set()
    for path in outputs:
        absolute = os.path.abspath(path)
        is_mask = os.path.basename(os.path.dirname(absolute)).lower() == "masks"
        channel = None
        if is_mask:
            base = safe_filename(os.path.splitext(os.path.basename(absolute))[0])
            channel = f"CMask - {base}"
            candidate = channel
            counter = 2
            while candidate.casefold() in used_channels:
                candidate = f"{channel} {counter}"
                counter += 1
            channel = candidate
            used_channels.add(channel.casefold())
        entries.append({
            "path": absolute,
            "name": _layer_name(absolute),
            "channel": channel,
        })
    return entries


def build_photoshop_jsx(outputs, psd_path, create_channels=True):
    """Build a self-contained Photoshop ExtendScript layer importer."""
    entries = _handoff_entries(outputs)
    if not entries:
        raise PhotoshopHandoffError("没有可导入 Photoshop 的输出文件")

    return """#target photoshop
// Generated by Collection Mask Exporter. Run with Photoshop: File > Scripts > Browse.
app.bringToFront();

(function () {
    var cmaskFiles = %s;
    var cmaskPsdPath = %s;
    var cmaskCreateChannels = %s;
    var target = null;
    var channelCount = 0;
    var channelErrors = [];

    function activateCompositeChannels(doc) {
        try {
            doc.activeChannels = doc.componentChannels;
        } catch (ignored) {
            var components = [];
            var count = (doc.mode == DocumentMode.GRAYSCALE) ? 1 : 3;
            for (var i = 0; i < count; i++) components.push(doc.channels[i]);
            doc.activeChannels = components;
        }
    }

    function loadActiveLayerTransparency() {
        var descriptor = new ActionDescriptor();
        var selection = new ActionReference();
        selection.putProperty(stringIDToTypeID("channel"), stringIDToTypeID("selection"));
        descriptor.putReference(stringIDToTypeID("null"), selection);
        var transparency = new ActionReference();
        transparency.putEnumerated(
            stringIDToTypeID("channel"), stringIDToTypeID("channel"),
            stringIDToTypeID("transparencyEnum")
        );
        descriptor.putReference(stringIDToTypeID("to"), transparency);
        executeAction(stringIDToTypeID("set"), descriptor, DialogModes.NO);
    }

    function activeLayerIsEmpty(doc) {
        var bounds = doc.activeLayer.bounds;
        return bounds[2].as("px") <= bounds[0].as("px") ||
               bounds[3].as("px") <= bounds[1].as("px");
    }

    function createAlphaChannel(doc, name) {
        app.activeDocument = doc;
        activateCompositeChannels(doc);
        doc.selection.deselect();
        if (activeLayerIsEmpty(doc)) {
            var emptyAlpha = doc.channels.add();
            emptyAlpha.name = name;
            activateCompositeChannels(doc);
            channelCount++;
            return;
        }
        loadActiveLayerTransparency();
        var alpha = doc.channels.add();
        alpha.name = name;
        doc.selection.store(alpha, SelectionType.REPLACE);
        doc.selection.deselect();
        activateCompositeChannels(doc);
        channelCount++;
    }

    try {
        for (var i = 0; i < cmaskFiles.length; i++) {
            var entry = cmaskFiles[i];
            var input = new File(entry.path);
            if (!input.exists) {
                throw new Error("CMask output is missing: " + entry.path);
            }
            var source = app.open(input);
            source.activeLayer.name = entry.name;
            if (target === null) {
                target = source;
            } else {
                var importedLayer = source.activeLayer.duplicate(
                    target, ElementPlacement.PLACEATBEGINNING
                );
                source.close(SaveOptions.DONOTSAVECHANGES);
                app.activeDocument = target;
                activateCompositeChannels(target);
                target.activeLayer = importedLayer || target.layers[0];
            }
            if (cmaskCreateChannels && entry.channel !== null) {
                try {
                    createAlphaChannel(target, entry.channel);
                } catch (alphaError) {
                    channelErrors.push(entry.channel + ": " + alphaError.message);
                    activateCompositeChannels(target);
                    target.selection.deselect();
                }
            }
        }

        if (target === null) {
            throw new Error("No CMask output was imported.");
        }
        var options = new PhotoshopSaveOptions();
        options.layers = true;
        options.alphaChannels = true;
        options.embedColorProfile = true;
        target.saveAs(new File(cmaskPsdPath), options, true, Extension.LOWERCASE);
        var summary = "CMask imported " + cmaskFiles.length + " layer(s) and " +
                      channelCount + " alpha channel(s).\\nSaved: " + cmaskPsdPath;
        if (channelErrors.length > 0) {
            summary += "\\n\\nAlpha channels skipped:\\n" + channelErrors.join("\\n");
        }
        alert(summary);
    } finally {
        // Deliberately leave the global Photoshop dialog mode untouched.
    }
}());
""" % (
        _jsx_literal(entries), _jsx_literal(os.path.abspath(psd_path)),
        "true" if create_channels else "false",
    )


def write_photoshop_handoff(scene, settings, outputs=None):
    outputs = list(outputs if outputs is not None else
                   (item.path for item in settings.last_outputs))
    outputs = [os.path.abspath(path) for path in outputs if path]
    if not outputs:
        raise PhotoshopHandoffError("请先导出蒙版或彩色 ID")
    missing = [path for path in outputs if not os.path.isfile(path)]
    if missing:
        raise PhotoshopHandoffError(
            f"最近输出中有 {len(missing)} 个文件已不存在：{missing[0]}"
        )

    root, _color_dir, _mask_dir = ensure_output_dirs(scene, settings)
    handoff_dir = os.path.join(root, "Photoshop")
    os.makedirs(handoff_dir, exist_ok=True)
    base = safe_filename(f"{blend_stem()}_cmask_photoshop")
    jsx_path = os.path.join(handoff_dir, base + "_import.jsx")
    psd_path = os.path.join(handoff_dir, base + ".psd")
    manifest_path = os.path.join(handoff_dir, base + "_handoff.json")

    create_channels = bool(getattr(settings, "photoshop_create_channels", True))
    entries = _handoff_entries(outputs)
    script = build_photoshop_jsx(outputs, psd_path, create_channels=create_channels)
    # A UTF-8 BOM keeps non-ASCII Collection names readable in ExtendScript.
    with open(jsx_path, "w", encoding="utf-8-sig", newline="\n") as handle:
        handle.write(script)

    payload = {
        "schema": "cmask.photoshop_handoff.v1",
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "blend": getattr(scene, "name", ""),
        "script": jsx_path,
        "psd": psd_path,
        "create_alpha_channels": create_channels,
        "outputs": [
            {"path": entry["path"], "layer": entry["name"],
             "channel": entry["channel"] if create_channels else None}
            for entry in entries
        ],
    }
    with open(manifest_path, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
    return jsx_path, manifest_path, psd_path
